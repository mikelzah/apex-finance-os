// Замеры вьюпорта. Влияет ровно на одно: высоту страницы.
//
// Что установлено покадрово по записи с iPhone 17 Pro Max (экран 440×956 CSS):
//
//   главная, документ 1879 — вьюпорт полный: панель 865–956, иконки 876–893,
//                            подписи 903–913, всё на месте;
//   журнал,  документ  894 — вьюпорт 894: панель заканчивается на 62 пикселя
//                            выше края экрана.
//
// Разница между экранами — прокручивается страница или укладывается ровно
// во вьюпорт. Лечится это высотой страницы: она считается от --full-height
// с запасом, поэтому прокрутка есть везде. Полную высоту замеряет этот модуль
// и отдаёт в CSS — единственное, на что он влияет. Ошибка в замере добавит
// пустой прокрутки и ничего больше: панель от него не зависит.
//
// Здесь же — цена трёх моих неверных попыток, чтобы к ним не вернуться.
//
// Первая: поправка считалась один раз на старте, на коротком экране-заглушке,
// и применялась ко всем экранам сразу. Панель ушла за край.
//
// Вторая: я решил, что видимая область остаётся полной при коротком вьюпорте,
// сравнив 956 из шапки раздела диагностики с 894 из строки журнала. Это были
// числа с разных экранов, и вывод из них не следовал.
//
// Третья и главная: поправка сдвигом панели вниз невозможна в принципе. На той
// же записи видно, что иконки встали правильно, а подписи, попавшие ниже низа
// вьюпорта, не нарисовались вовсе. Содержимое закреплённого слоя ниже вьюпорта
// не отрисовывается — сдвигать панель туда бессмысленно. Отсюда и правило:
// вьюпорт лечим вьюпортом, а не смещениями.

// Самый высокий вьюпорт, наблюдённый при этой ширине. Ширина в паре с высотой
// потому, что при повороте вьюпорт меняется целиком.
let peak = { width: 0, height: 0 };

// Насколько высоту страницы вообще разрешено задирать сверх вьюпорта. Пустая
// прокрутка безвредна, но не бесконечно же.
const MAX_STRETCH = 400;

const seen = new Map();

export function standalone() {
  if (navigator.standalone === true) return true;
  return Boolean(window.matchMedia && window.matchMedia('(display-mode: standalone)').matches);
}

export function measure() {
  const inner = window.innerHeight || 0;
  const vv = window.visualViewport;
  const doc = document.documentElement;
  const scr = window.screen || {};
  const screenH = scr.height || 0;
  const width = window.innerWidth;

  if (peak.width !== width) peak = { width, height: inner };
  else if (inner > peak.height) peak.height = inner;

  // Высоте экрана верим только в отдельном окне, в портрете и при совпавших
  // ширинах — последнее прямо проверяет, что экран и вьюпорт меряются в одних
  // пикселях. Рядом второй источник: самый высокий вьюпорт, который уже
  // наблюдался. Оба идут только на увеличение высоты страницы.
  const trusted = standalone() && scr.width === width && width <= inner;
  const full = Math.min(
    Math.max(inner, trusted ? screenH : 0, peak.height),
    inner + MAX_STRETCH,
  );

  return {
    inner,
    visible: vv ? Math.round(vv.height * (vv.scale || 1)) : inner,
    screenH,
    full,
    scrollHeight: doc.scrollHeight,
    scrollable: doc.scrollHeight > inner,
    // Ради этого признака раздел и существует: если вьюпорт короче экрана,
    // панель заканчивается выше края, и никакой правкой стилей панели этого
    // не исправить — только прокруткой страницы.
    short: screenH > inner,
    standalone: standalone(),
  };
}

let applied = null;

/**
 * Отдать полную высоту в CSS.
 *
 * От неё считается высота страницы, и только от этого. Завышенное значение
 * добавит пустой прокрутки — неприятно, но безобидно. Заниженное вернёт
 * исходную задачу, но не сломает ничего нового.
 *
 * Пишем только при изменении: запись свойства в корне обесценивает стиль
 * всего документа, а вызывается apply дважды на каждую отрисовку — значение
 * при этом почти всегда одно и то же.
 */
export function apply() {
  const full = measure().full;
  if (full === applied) return;
  applied = full;
  document.documentElement.style.setProperty('--full-height', `${full}px`);
}

export function watch() {
  apply();
  window.addEventListener('resize', apply);
  // На поворот iOS отвечает не сразу: размеры на момент события ещё старые.
  window.addEventListener('orientationchange', () => setTimeout(apply, 250));
}

/**
 * Запомнить замер экрана.
 *
 * Вызывается после отрисовки — и ещё раз, когда раскладка успокоится. Второй
 * замер обязателен: iOS меняет высоту вьюпорта не в тот же кадр, и первое
 * чтение бывает от предыдущего экрана. Ровно на этом я один раз построил
 * неверный вывод, приняв запоздавшее значение за настоящее.
 */
export function note(key) {
  apply();
  seen.set(key, measure());
  requestAnimationFrame(() => setTimeout(() => {
    apply();
    seen.set(key, measure());
  }, 200));
}

export function records() {
  return [...seen.entries()];
}
